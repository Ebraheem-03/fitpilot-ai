"""Eval report files: `plans-<prompt_version>.json` (aggregates) + `.md` rendered from it.

One report per prompt version. Runs are merged by (mode, model, effort): rerunning one replaces
it, other runs stay. Runs recorded under a different prompt hash are stale and dropped. The text
between the NOTES markers in the markdown is hand-written and kept on re-render; everything else
is generated. Aggregates and up to 3 failures per run only: no prompts, no model output.
`make eval-ai` runs prettier on both files afterwards (`pnpm format:check` covers docs/).
"""

import json
import re
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

REPORT_FORMAT = 1
NOTES_BEGIN = "<!-- BEGIN NOTES (hand-written, kept on re-render) -->"
NOTES_END = "<!-- END NOTES -->"
_NOTES_RE = re.compile(re.escape(NOTES_BEGIN) + r"(.*?)" + re.escape(NOTES_END), re.DOTALL)


def run_key(run: Mapping[str, Any]) -> tuple[str, str, str]:
    return (run["mode"], run["model"], run["reasoning_effort"])


def merge_runs(
    existing: Mapping[str, Any] | None, run: Mapping[str, Any], prompt_sha256: str
) -> list[dict[str, Any]]:
    runs: list[dict[str, Any]] = []
    if existing and existing.get("prompt_sha256") == prompt_sha256:
        runs = [dict(r) for r in existing.get("runs", []) if run_key(r) != run_key(run)]
    runs.append(dict(run))
    return sorted(runs, key=lambda r: (r["mode"] != "live", r["model"], r["reasoning_effort"]))


def write_report(
    md_path: Path,
    run: Mapping[str, Any],
    *,
    prompt_version: str,
    prompt_sha256: str,
    suite_version: int,
    suite_profiles: int,
    gate: Mapping[str, Any],
    fresh: bool = False,
) -> dict[str, Any]:
    json_path = md_path.with_suffix(".json")
    existing = None if fresh or not json_path.exists() else json.loads(json_path.read_text())
    report = {
        "report_format": REPORT_FORMAT,
        "prompt_version": prompt_version,
        "prompt_sha256": prompt_sha256,
        "suite_version": suite_version,
        "suite_profiles": suite_profiles,
        "gate": dict(gate),
        "runs": merge_runs(existing, run, prompt_sha256),
    }
    notes = ""
    if md_path.exists():
        match = _NOTES_RE.search(md_path.read_text())
        notes = match.group(1) if match else ""
    md_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(report, indent=2) + "\n")
    md_path.write_text(render_markdown(report, notes))
    return report


# --- Markdown.


def _pct(r: Mapping[str, Any]) -> str:
    if r["rate"] is None:
        return "n/a"
    return f"{r['n']}/{r['of']} ({r['rate']:.0%})"


def _s(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1f}"


def _usd(value: float | None) -> str:
    return "n/a" if value is None else f"${value:.4f}"


def _counts(counts: Mapping[str, int]) -> str:
    return ", ".join(f"{k or '(none)'}: {v}" for k, v in counts.items()) or "none"


def _row(cells: Sequence[object]) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _table(header: Sequence[str], rows: Sequence[Sequence[object]]) -> list[str]:
    return [_row(header), _row(["---"] * len(header)), *(_row(r) for r in rows)]


def run_label(run: Mapping[str, Any]) -> str:
    if run["mode"] == "offline":
        return "offline (fake provider, scripted)"
    return f"`{run['model']}` · {run['reasoning_effort']}"


def render_markdown(report: Mapping[str, Any], notes: str = "") -> str:
    runs = report["runs"]
    gate = report["gate"]
    out = [
        f"# Plan-generation eval: `{report['prompt_version']}`",
        "",
        "<!-- Generated by `uv run python -m app.services.evaluation.plans` (services/api). "
        "Edit only between the NOTES markers. -->",
        "",
        f"- prompt_version: `{report['prompt_version']}`",
        f"- prompt_sha256: `{report['prompt_sha256']}`",
        f"- suite: `data/evaluation-fixtures/ai/plans/suite.json` v{report['suite_version']}, "
        f"{report['suite_profiles']} synthetic profiles",
        f"- gate: valid after repair ≥ {gate['valid_after_repair_min']:.0%} of feasible plans; "
        f"constraint adherence of accepted plans ≥ {gate['constraint_adherence_min']:.0%}; "
        f"expected escalations ≥ {gate['expected_escalation_min']:.0%}; false escalations ≤ "
        f"{gate['false_escalation_max']:.0%}; at least {gate['min_scored_plans']} plans scored",
        "",
        NOTES_BEGIN,
        *(["", notes.strip(), ""] if notes.strip() else []),
        NOTES_END,
        "",
        "## Summary",
        "",
    ]
    rows = []
    for run in runs:
        a = run["aggregate"]
        v, e, lat, tok = a["validity"], a["escalation"], a["latency_s"], a["tokens"]
        rows.append(
            [
                run_label(run),
                f"{a['scored']}/{run['planned']}",
                _pct(v["valid_first_try"]),
                _pct(v["valid_after_repair"]),
                _pct(a["constraints"]["all"]),
                _pct(e["expected_escalations"]),
                _pct(e["false_escalations"]),
                f"{_s(lat['plan_p50'])} / {_s(lat['plan_p95'])}",
                f"{_s(lat['first_call_p50'])} / {_s(lat['first_call_p95'])}",
                f"{tok['per_plan_in']} / {tok['per_plan_out']}",
                _usd(a["cost_usd"]["list_per_plan"]),
                a["rate_limited_429"],
                "pass" if not run["gate_failures"] else "**fail**",
            ]
        )
    out += _table(
        [
            "run",
            "plans scored / planned",
            "valid first try",
            "valid after 1 repair",
            "accepted plans within all constraints",
            "expected escalations",
            "false escalations",
            "latency per plan p50 / p95 (s)",
            "first call p50 / p95 (s)",
            "tokens per plan (in / out)",
            "list cost per plan",
            "429s",
            "gate",
        ],
        rows,
    )
    out += [
        "",
        "Validity and false escalations are over feasible profiles (`expect.outcome: active`). "
        "Latency is wall-clock per plan including the repair call and any in-request 429 wait. "
        "List cost is at Groq list prices; the free tier bills $0.",
        "",
        "## Runs",
        "",
    ]
    for run in runs:
        a = run["aggregate"]
        v = a["validity"]
        out += [
            f"### {run_label(run)}",
            "",
            f"- {run['started_at']} → {run['finished_at']}, {run['runs_per_fixture']} run(s) "
            f"per profile, provider `{run['provider']}`",
            f"- scored {a['scored']} of {run['planned']} planned plans; errors: "
            f"{_counts(a['errors'])}",
        ]
        if run.get("stopped"):
            out.append(
                f"- **stopped early: {run['stopped']}.** These results are partial; profiles "
                "not reached are missing from the per-profile table."
            )
        out += [
            f"- schema-valid first try {_pct(v['schema_valid_first_try'])}, after repair "
            f"{_pct(v['schema_valid_after_repair'])}; repaired {_pct(v['repaired'])}",
            f"- first-attempt issue codes (all plans): {_counts(v['first_issue_codes'])}",
            f"- calls {a['tokens']['calls']}, tokens in/out {a['tokens']['total_in']} / "
            f"{a['tokens']['total_out']}, list cost {_usd(a['cost_usd']['list_total'])}",
            f"- gate: {'pass' if not run['gate_failures'] else '; '.join(run['gate_failures'])}",
            "",
        ]
        c, p = a["constraints"], a["properties"]
        out += _table(
            ["catalogue", "equipment", "days", "session length", "prescription"],
            [
                [
                    _pct(c[k])
                    for k in ("catalogue", "equipment", "days", "session_length", "prescription")
                ]
            ],
        )
        out += [
            "",
            f"Expected properties (reported, not gated): shortest day ≥ `min_fill` of the session "
            f"{_pct(p['min_fill'])}; owned equipment used {_pct(p['uses_equipment'])}. "
            f"`either` profile outcomes: {_counts(a['escalation']['either_outcomes'])}.",
            "",
        ]
        if a["failures"]:
            out += ["Representative failures:", ""]
            for f in a["failures"]:
                detail = "; ".join(f["final_issues"]) or f["error"] or "repaired"
                violated = (
                    f" violated: {', '.join(f['violated_constraints'])}."
                    if f["violated_constraints"]
                    else ""
                )
                out.append(
                    f"- `{f['fixture_id']}` expected {f['expected']}, got **{f['result']}**; "
                    f"first attempt: {', '.join(f['first_issue_codes']) or '-'}; final: "
                    f"{detail}.{violated}"
                )
            out.append("")
    out += ["## Per profile", "", "Cells: valid first try / repaired / escalated / error.", ""]
    ids = sorted({fid for run in runs for fid in run["aggregate"]["per_fixture"]})
    expected = {fid: exp for run in runs for fid, exp in run.get("expected", {}).items()}
    prof_rows = []
    for fid in ids:
        cells: list[object] = [f"`{fid}`", expected.get(fid, "")]
        for run in runs:
            r = run["aggregate"]["per_fixture"].get(fid)
            cells.append(
                "-"
                if r is None
                else f"{r['valid_first_try']}/{r['repaired']}/{r['escalated']}/{r['error']}"
            )
        prof_rows.append(cells)
    out += _table(["profile", "expected", *(run_label(r) for r in runs)], prof_rows)
    return "\n".join(out) + "\n"
